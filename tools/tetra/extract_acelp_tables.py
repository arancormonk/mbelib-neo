"""Extract the TETRA speech codec codebooks from a local copy of ETSI's archive.

The TETRA decoder (EN 300 395-2 clause 4) needs two tables that exist only as data
files in the C code archive attached to EN 300 395-2: the split-VQ LSP codebooks
(C-CODE/CLSP_334.TAB) and the gain codebook (C-CODE/ENER_QUA.TAB). This tool reads
those two members, and nothing else, from the archive the user downloaded from ETSI,
checks the archive against the published versions it knows, and writes
src/tetra/tetra_acelp_codebooks.c with the values and their provenance. The arrays are
declared in src/internal/tetra_acelp_codebooks.h, which is not generated.

    tools/tetra/extract_acelp_tables.py /path/to/en_30039502v010303p0.zip
    tools/tetra/extract_acelp_tables.py --check /path/to/en_30039502v010301p0.zip

The archive is never extracted to disk and no other member is opened.
"""

DESCRIPTION = "Extract the TETRA speech codec codebooks from a local copy of ETSI's archive."

import argparse
import hashlib
import io
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = ROOT / "src" / "tetra" / "tetra_acelp_codebooks.c"

# Archives attached to EN 300 395-2 whose C-CODE members are identical (name, size, CRC-32).
KNOWN_ARCHIVES = {
    "1fe18c4773c8ccb52ef23ca5b4a0b0841b38d54ddd5d9c7d86eb8b060f132f39": "en_30039502v010301p0.zip (V1.3.1)",
    "06fa7611fc92d46a2c0fb173aa3e007dc80a0c3f03b94eb8ed181c9b7e5f3034": "en_30039502v010303p0.zip (V1.3.3)",
}
LSP_MEMBER = "C-CODE/CLSP_334.TAB"
GAIN_MEMBER = "C-CODE/ENER_QUA.TAB"

# (member, array name in the member, C name, rows, columns, description)
TABLES = (
    (LSP_MEMBER, "dico1_clsp", "tetra_lsp_cb1", 256, 3, "LSP split VQ, q1..q3 (8 bits), Q15 cosine domain"),
    (LSP_MEMBER, "dico2_clsp", "tetra_lsp_cb2", 512, 3, "LSP split VQ, q4..q6 (9 bits), Q15 cosine domain"),
    (LSP_MEMBER, "dico3_clsp", "tetra_lsp_cb3", 512, 4, "LSP split VQ, q7..q10 (9 bits), Q15 cosine domain"),
    (GAIN_MEMBER, "t_qua_ener", "tetra_gain_cb", 64, 2, "gain VQ (6 bits), Q8, pairs in the archive's order"),
)

_ELEMENT = re.compile(r"^(-?\d+)(?:\s*\*\s*(\d+))?$")


class ExtractError(Exception):
    pass


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def parse_array(text, name, count):
    """Return the values of `static Word16 <name>[...] = { ... };` as integers.

    Elements are integer literals, optionally multiplied by an integer literal
    ("16231 * 2"); anything else is rejected rather than interpreted.
    """
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    match = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\}\s*;", text, flags=re.S)
    if not match:
        raise ExtractError(f"array {name} not found")
    values = []
    for element in match.group(1).split(","):
        element = element.strip()
        if not element:
            continue
        parsed = _ELEMENT.match(element)
        if not parsed:
            raise ExtractError(f"{name}: unexpected element {element!r}")
        value = int(parsed.group(1)) * (int(parsed.group(2)) if parsed.group(2) else 1)
        if not -32768 <= value <= 32767:
            raise ExtractError(f"{name}: {element!r} does not fit in 16 bits")
        values.append(value)
    if len(values) != count:
        raise ExtractError(f"{name}: {len(values)} values, expected {count}")
    return values


def read_members(archive_path, known=None):
    """Return ({member: bytes}, archive description) after checking the archive."""
    known = KNOWN_ARCHIVES if known is None else known
    data = Path(archive_path).read_bytes()
    digest = sha256(data)
    if digest not in known:
        raise ExtractError(f"{archive_path}: SHA-256 {digest} is not a known EN 300 395-2 archive")
    # Extract from the bytes that were hashed, not from the path again.
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        members = {name: archive.read(name) for name in (LSP_MEMBER, GAIN_MEMBER)}
    return members, known[digest]


def render(members, known=None):
    known = KNOWN_ARCHIVES if known is None else known
    lines = [
        "// SPDX-License-Identifier: LicenseRef-ETSI-EN-300-395-2-data",
        "/* Generated by tools/tetra/extract_acelp_tables.py; do not edit. */",
        "/*",
        " * TETRA speech codec codebooks: numeric data from the C code archive attached to",
        " * ETSI EN 300 395-2 (TETRA; Speech codec for full-rate traffic channel; Part 2:",
        " * TETRA codec), (C) ETSI. Only the values are copied; no ETSI code is used.",
        " * This file is not covered by the project's GPL grant, and no licence to the data",
        " * is known: see LICENSES/LicenseRef-ETSI-EN-300-395-2-data.txt.",
        " *",
        " * Archives with identical members (SHA-256):",
    ]
    lines += [f" *   {name}: {digest}" for digest, name in sorted(known.items(), key=lambda item: item[1])]
    lines.append(" * Members (SHA-256):")
    lines += [f" *   {name}: {sha256(members[name])}" for name in (LSP_MEMBER, GAIN_MEMBER)]
    lines += [
        " * Entries written as \"N * 2\" in the archive are stored evaluated.",
        " */",
        "",
        "#include \"tetra_acelp_codebooks.h\"",
        "",
        "// clang-format off",
    ]
    for member, name, c_name, rows, columns, description in TABLES:
        text = members[member].decode("ascii")
        values = parse_array(text, name, rows * columns)
        lines += ["", f"/* {member} {name}: {description}. */"]
        lines.append(f"const int16_t {c_name}[{rows}][{columns}] = {{")
        for row in range(rows):
            vector = values[row * columns:(row + 1) * columns]
            lines.append("    {" + ", ".join(f"{v:6d}" for v in vector) + "},")
        lines.append("};")
    lines += ["", "// clang-format on", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=DESCRIPTION)
    parser.add_argument("archive", type=Path, help="local copy of en_30039502v0103(01|03)p0.zip from ETSI")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="C file to write")
    parser.add_argument("--check", action="store_true", help="compare with the existing file instead of writing")
    args = parser.parse_args(argv)
    try:
        members, description = read_members(args.archive)
        text = render(members)
    except (ExtractError, OSError, KeyError, zipfile.BadZipFile, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if args.check:
        try:
            current = args.output.read_text(encoding="ascii")
        except OSError as error:
            print(f"error: {error}", file=sys.stderr)
            return 2
        if current != text:
            print(f"{args.output} differs from the tables in {description}", file=sys.stderr)
            return 1
        print(f"{args.output} matches {description}")
        return 0
    args.output.write_text(text, encoding="ascii")
    print(f"wrote {args.output} from {description}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
