"""Generate the computed constants of the TETRA ACELP decoder.

Every value here follows from a formula, so the header is reproducible:

- log2/pow2 interpolation tables (33 entries each) for the gain decoder;
- the two 32-tap fractional-delay filters of the adaptive codebook, a Hamming-windowed sinc
  truncated at +-48 in thirds of a sample (EN 300 395-2 clause 4.2.2.4), sampled at the +1/3
  and -1/3 positions and rounded to Q15;
- the powers of gamma1 = 0.75 and gamma2 = 0.85 used to weight A(z) for the codevector shaping
  filter F(z) (clause 4.1, equation 4), as recursive Q15 products rounded at each step.

    tools/tetra/gen_acelp_constants.py            # rewrite src/internal/tetra_acelp_constants.h
    tools/tetra/gen_acelp_constants.py --check    # exit 1 if the committed header differs
"""

import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src" / "internal" / "tetra_acelp_constants.h"


def q15_mult_r(a, b):
    return (a * b + 0x4000) >> 15


def log2_table():
    return [min(32767, int(math.floor(math.log2(1 + i / 32) * 32768 + 0.5))) for i in range(33)]


def pow2_table():
    return [min(32767, int(math.floor(2 ** (i / 32) * 16384 + 0.5))) for i in range(33)]


def interp_filter(frac):
    """Taps for the past-excitation samples exc[n - T0 + k] (k from the returned range)."""
    taps = range(-16, 16) if frac > 0 else range(-15, 17)
    out = []
    for k in taps:
        t = -k - frac / 3
        sinc = 1.0 if t == 0 else math.sin(math.pi * t) / (math.pi * t)
        window = 0.54 + 0.46 * math.cos(math.pi * 3 * t / 48)
        out.append(int(math.floor(sinc * window * 32768 + 0.5)))
    return out


def gamma_powers(gamma_q15):
    out = [gamma_q15]
    for _ in range(9):
        out.append(q15_mult_r(out[-1], gamma_q15))
    return out


def array(name, values, per_line=8):
    lines = [f"static const int16_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(f"{v}" for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return lines


def render():
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "/* Generated by tools/tetra/gen_acelp_constants.py; do not edit. */",
        "/*",
        " * Computed constants of the TETRA ACELP decoder; see the generator for the formulas.",
        " */",
        "",
        "#ifndef MBELIB_NEO_INTERNAL_TETRA_ACELP_CONSTANTS_H",
        "#define MBELIB_NEO_INTERNAL_TETRA_ACELP_CONSTANTS_H",
        "",
        "#include <stdint.h>",
        "",
        "// clang-format off",
        "",
        "/* round(32768 * log2(1 + i/32)), i = 0..32, the last entry limited to 32767. */",
    ]
    lines += array("tetra_log2_tab", log2_table())
    lines += ["", "/* round(16384 * 2^(i/32)), i = 0..32, the last entry limited to 32767. */"]
    lines += array("tetra_pow2_tab", pow2_table())
    lines += ["", "/* Fractional delay +1/3: taps for exc[n - T0 + k], k = -16..15 (Q15). */"]
    lines += array("tetra_interp_p13", interp_filter(1))
    lines += ["", "/* Fractional delay -1/3: taps for exc[n - T0 + k], k = -15..16 (Q15). */"]
    lines += array("tetra_interp_m13", interp_filter(-1))
    lines += ["", "/* 0.75^i and 0.85^i, i = 1..10 (Q15), recursive rounded products. */"]
    lines += array("tetra_gamma1_pow", gamma_powers(24576), 10)
    lines += array("tetra_gamma2_pow", gamma_powers(27853), 10)
    lines += ["", "// clang-format on", "", "#endif /* MBELIB_NEO_INTERNAL_TETRA_ACELP_CONSTANTS_H */", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate the TETRA ACELP decoder's computed constants.")
    parser.add_argument("--check", action="store_true", help="compare with the committed header instead of writing")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
